    def search_html(keyword):
        key = str(keyword or "").strip().lower()
        if not key:
            return HelpContentService.full_html()
        matched = []
        for name, html in HelpContentService.SECTIONS:
            plain = (name + " " + html).lower()
            if key in plain:
                matched.append(f"<h1 class='search-title'>搜尋結果：{name}</h1>{html}")
        if not matched:
            matched = [f"<h2>沒有找到「{keyword}」</h2><p>可以嘗試搜尋：採購、庫存、客戶需求、供應商、調撥、貨櫃、匯出、帳號、授權。</p>"]
